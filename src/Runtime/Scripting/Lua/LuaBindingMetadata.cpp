#include "Headers/Runtime/Scripting/Lua/LuaBindingMetadata.hpp"

#include <algorithm>
#include <fstream>
#include <utility>

#include <spdlog/spdlog.h>

namespace {
    std::vector<LuaBindingMetadata::TypeDoc> registeredTypes;
    std::vector<LuaBindingMetadata::CallbackDoc> registeredCallbacks;
    std::vector<LuaBindingMetadata::PropertyDoc> registeredScriptGlobals;
    std::vector<LuaBindingMetadata::MethodDoc> registeredScriptFunctions;
}

namespace LuaBindingMetadata {
    void RegisterType(TypeDoc type) {
        registeredTypes.push_back(std::move(type));
    }

    const std::vector<TypeDoc>& AllTypes() {
        return registeredTypes;
    }

    void RegisterCallback(CallbackDoc callback) {
        registeredCallbacks.push_back(std::move(callback));
    }

    const std::vector<CallbackDoc>& AllCallbacks() {
        return registeredCallbacks;
    }

    void RegisterScriptGlobal(PropertyDoc global) {
        registeredScriptGlobals.push_back(std::move(global));
    }

    const std::vector<PropertyDoc>& AllScriptGlobals() {
        return registeredScriptGlobals;
    }

    void RegisterScriptFunction(MethodDoc function) {
        registeredScriptFunctions.push_back(std::move(function));
    }

    const std::vector<MethodDoc>& AllScriptFunctions() {
        return registeredScriptFunctions;
    }

    std::string FunctionSignature(const MethodDoc& function) {
        std::string signature = function.name + "(";

        for (std::size_t i = 0; i < function.params.size(); ++i) {
            if (i > 0) signature += ", ";
            signature += function.params[i].name + ": " + function.params[i].luaType;
        }

        signature += ")";
        if (!function.returnType.empty()) signature += " -> " + function.returnType;
        return signature;
    }

    const std::vector<std::string>& LuaKeywordNames() {
        static const std::vector<std::string> keywords = {
            "and", "break", "do", "else", "elseif", "end", "false", "for", "function",
            "goto", "if", "in", "local", "nil", "not", "or", "repeat", "return", "then",
            "true", "until", "while"
        };
        return keywords;
    }

    bool IsLuaKeyword(const std::string_view name) {
        return std::ranges::find(LuaKeywordNames(), name) != LuaKeywordNames().end();
    }

    bool IsEngineName(const std::string_view name) {
        return std::ranges::find(registeredCallbacks, name, &CallbackDoc::name) != registeredCallbacks.end()
            || std::ranges::find(registeredScriptGlobals, name, &PropertyDoc::name) != registeredScriptGlobals.end()
            || std::ranges::find(registeredScriptFunctions, name, &MethodDoc::name) != registeredScriptFunctions.end()
            || std::ranges::find(registeredTypes, name, &TypeDoc::name) != registeredTypes.end();
    }

    std::string CallbackSignature(const CallbackDoc& callback) {
        std::string signature = callback.name + "(";

        for (std::size_t i = 0; i < callback.params.size(); ++i) {
            if (i > 0) signature += ", ";
            signature += callback.params[i].name + ": " + callback.params[i].luaType;
        }

        return signature + ")";
    }

    std::string CallbackOwnerNote(const CallbackOwner owner) {
        switch (owner) {
            case CallbackOwner::Entity: return "Entity scripts only. ";
            case CallbackOwner::Sector: return "Sector scripts only. ";
            case CallbackOwner::Any: break;
        }
        return {};
    }

    bool GenerateLuaLSStub(const std::string& outputPath) {
        std::ofstream file(outputPath);

        if (!file.is_open()) {
            spdlog::error("Failed to open '{}' for LuaLS stub generation", outputPath);
            return false;
        }

        file << "---@meta\n";
        file << "-- Auto-generated by Tilky's LuaBindingMetadata registry - do not edit by\n";
        file << "-- hand, regenerate instead. Point LuaLS's Lua.workspace.library at this\n";
        file << "-- file's folder for autocomplete/hover/signature-help on Tilky's scripting API.\n\n";

        for (const TypeDoc& type : registeredTypes) {
            if (!type.doc.empty()) file << "---" << type.doc << "\n";

            if (!type.enumValues.empty()) {
                file << "---@enum " << type.name << "\n" << type.name << " = {\n";

                for (const EnumValueDoc& value : type.enumValues) {
                    if (!value.doc.empty()) file << "    ---" << value.doc << "\n";
                    file << "    " << value.name << " = " << value.value << ",\n";
                }

                file << "}\n\n";
                continue;
            }

            file << "---@class " << type.name << "\n";

            for (const PropertyDoc& prop : type.properties) {
                file << "---@field " << prop.name << " " << prop.luaType;
                if (!prop.doc.empty()) file << " @" << prop.doc;
                file << "\n";
            }

            if (type.isGlobalTable) file << type.name << " = {}\n\n";
            else file << "local " << type.name << " = {}\n\n";

            for (const MethodDoc& method : type.methods) {
                if (!method.doc.empty()) file << "---" << method.doc << "\n";

                for (const ParamDoc& param : method.params)
                    file << "---@param " << param.name << " " << param.luaType << "\n";

                if (!method.returnType.empty()) file << "---@return " << method.returnType << "\n";

                file << "function " << type.name << (type.isGlobalTable ? "." : ":") << method.name << "(";

                for (std::size_t i = 0; i < method.params.size(); ++i) {
                    if (i > 0) file << ", ";
                    file << method.params[i].name;
                }

                file << ") end\n\n";
            }
        }

        for (const PropertyDoc& global : registeredScriptGlobals) {
            if (!global.doc.empty()) file << "---" << global.doc << "\n";
            file << "---@type " << global.luaType << "\n" << global.name << " = nil\n\n";
        }

        for (const MethodDoc& function : registeredScriptFunctions) {
            if (!function.doc.empty()) file << "---" << function.doc << "\n";

            for (const ParamDoc& param : function.params)
                file << "---@param " << param.name << " " << param.luaType << "\n";

            if (!function.returnType.empty()) file << "---@return " << function.returnType << "\n";

            file << "function " << function.name << "(";

            for (std::size_t i = 0; i < function.params.size(); ++i) {
                if (i > 0) file << ", ";
                file << function.params[i].name;
            }

            file << ") end\n\n";
        }

        // Callbacks are defined by the script, not the engine - declaring
        // them here gives LuaLS their names, parameters and docs.
        for (const CallbackDoc& callback : registeredCallbacks) {
            file << "---" << CallbackOwnerNote(callback.owner) << callback.doc << "\n";

            for (const ParamDoc& param : callback.params)
                file << "---@param " << param.name << " " << param.luaType << "\n";

            file << "function " << callback.name << "(";

            for (std::size_t i = 0; i < callback.params.size(); ++i) {
                if (i > 0) file << ", ";
                file << callback.params[i].name;
            }

            file << ") end\n\n";
        }

        return true;
    }
}
